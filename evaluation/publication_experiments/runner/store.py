"""Append-only raw store.

raw/attempts.jsonl  - one line per ATTEMPT. Written before any parsing. Never
                      rewritten, never rewound. This is the source of truth.
raw/index.jsonl     - one line per ASSESSMENT when it reaches a terminal state.
parsed/records.jsonl- DERIVED. Regenerated by rescore.py from attempts.jsonl.
                      Safe to delete at any time.
"""
from __future__ import annotations
import json, os
from pathlib import Path
from typing import Any, Iterator


class AppendOnlyJSONL:
    """Append + flush + fsync per line, so a crash cannot lose a stored attempt."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._fh = None

    def append(self, record: dict[str, Any]) -> None:
        if self._fh is None:
            self._fh = self.path.open("a", encoding="utf-8")
        self._fh.write(json.dumps(record, ensure_ascii=False, default=str) + "\n")
        self._fh.flush()
        os.fsync(self._fh.fileno())

    def close(self) -> None:
        if self._fh is not None:
            self._fh.close()
            self._fh = None

    def __enter__(self): return self
    def __exit__(self, *a): self.close()

    def read(self) -> Iterator[dict]:
        if not self.path.exists():
            return
        with self.path.open(encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    yield json.loads(line)


class DuplicateAssessment(RuntimeError):
    """A terminal record already exists for this (cell_id, sample_id)."""


class RunStore:
    """Directory layout for one experiment run."""

    def __init__(self, run_dir: str | Path):
        self.run_dir = Path(run_dir)
        for sub in ("raw", "parsed", "logs", "checkpoints", "summaries"):
            (self.run_dir / sub).mkdir(parents=True, exist_ok=True)
        self.attempts = AppendOnlyJSONL(self.run_dir / "raw" / "attempts.jsonl")
        self.index = AppendOnlyJSONL(self.run_dir / "raw" / "index.jsonl")
        self._terminal: dict[tuple[str, str], dict] = {}
        self._load_terminal()

    # ── resume state ─────────────────────────────────────────────────────────
    def _load_terminal(self) -> None:
        for rec in self.index.read():
            key = (rec.get("cell_id", ""), rec.get("sample_id", ""))
            self._terminal[key] = rec

    def terminal_record(self, cell_id: str, sample_id: str) -> dict | None:
        return self._terminal.get((cell_id, sample_id))

    def completed_count(self) -> int:
        return len(self._terminal)

    # ── writes ───────────────────────────────────────────────────────────────
    def append_attempt(self, attempt: dict) -> None:
        self.attempts.append(attempt)

    SUPERSEDABLE = frozenset({"RETRIES_EXHAUSTED"})

    def close_assessment(self, index_record: dict, *, allow_supersede: bool = False) -> None:
        """Write the terminal index line for one assessment.

        A second terminal record for the same (cell_id, sample_id) is refused, which is
        what stops an accidental re-run from silently duplicating data. The single
        exception is an EXPLICIT re-dispatch of an assessment whose retries were
        exhausted: the new line records `supersedes`, and the superseded line stays in
        the file, because the store is append-only.
        """
        key = (index_record["cell_id"], index_record["sample_id"])
        prior = self._terminal.get(key)
        if prior is not None:
            if not (allow_supersede and prior.get("final_outcome_class") in self.SUPERSEDABLE):
                raise DuplicateAssessment(
                    f"terminal record already exists for {key}; refusing to write a second one"
                )
            index_record = dict(index_record, supersedes=prior.get("assessment_uuid"),
                                supersedes_outcome=prior.get("final_outcome_class"))
        self.index.append(index_record)
        self._terminal[key] = index_record

    def write_json(self, relative: str, obj: Any) -> Path:
        p = self.run_dir / relative
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(obj, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
        return p

    def close(self) -> None:
        self.attempts.close()
        self.index.close()
